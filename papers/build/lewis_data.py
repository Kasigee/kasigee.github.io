"""Write ../lewis-data.js for the Lewis strength scene: the Figure 4 free energies (lewis_figure4.json)
and a 3D model of the NIPAM monomer residue the paper uses, N-isopropyl-2-methylbutanamide (the
saturated repeat unit drawn in its figures). The geometry is an RDKit ETKDG + MMFF94 structure made
for this page, not the paper's DFTB-optimised complexes, which aren't published.

usage: python3 lewis_data.py lewis_figure4.json ../lewis-data.js"""
import json, sys
from rdkit import Chem
from rdkit.Chem import AllChem

data = json.load(open(sys.argv[1]))
mol = Chem.AddHs(Chem.MolFromSmiles('CCC(C)C(=O)NC(C)C'))
AllChem.EmbedMolecule(mol, randomSeed=2019)
AllChem.MMFFOptimizeMolecule(mol)
conf = mol.GetConformer()
atoms = [[a.GetSymbol(), *[round(v, 3) for v in conf.GetAtomPosition(a.GetIdx())]] for a in mol.GetAtoms()]
bonds = [[b.GetBeginAtomIdx(), b.GetEndAtomIdx(), int(b.GetBondTypeAsDouble())] for b in mol.GetBonds()]
o = next(a.GetIdx() for a in mol.GetAtoms() if a.GetSymbol() == 'O')
n = next(a.GetIdx() for a in mol.GetAtoms() if a.GetSymbol() == 'N')
c = next(nb.GetIdx() for nb in mol.GetAtomWithIdx(o).GetNeighbors())
h = next(nb.GetIdx() for nb in mol.GetAtomWithIdx(n).GetNeighbors() if nb.GetSymbol() == 'H')
out = {k: data[k] for k in ('lewis', 'bound', 'effective', 'cation_O_distance_water_Cl')}
out['nipam'] = {'atoms': atoms, 'bonds': bonds, 'O': o, 'C': c, 'N': n, 'H': h}
with open(sys.argv[2], 'w') as f:
    f.write("// Data for the Lewis strength scene in paper-visuals.js. Generated by build/lewis_data.py; do not edit by hand.\n")
    f.write("// Ion-NIPAM free energies (kcal/mol) read from Figure 4 of Gregory et al., J. Phys. Chem. A 2019, 123, 6420,\n")
    f.write("// doi:10.1021/acs.jpca.9b04004 (the paper gives them only as a plot; about +/- 0.5 kcal/mol). Lewis strengths are\n")
    f.write("// Marcus's, as listed in the paper. The NIPAM residue geometry is an RDKit/MMFF94 model made for this page.\n")
    f.write("export const LEWIS = " + json.dumps(out, separators=(',', ':')) + ";\n")
print(len(atoms), 'atoms; O', o, 'N', n, 'H', h)
