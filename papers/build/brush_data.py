"""Write ../brush-data.js for the brush scene: the volume fraction profiles of Murdoch et al.,
Macromolecules 49, 6050 (2016), rebuilt from the fitted parameters in its Supporting Information.

usage: python3 brush_data.py brush_tables.json ../brush-data.js

Conditions are checked against the paper's Figure 5 (twice the first moment of each profile, read off
the figure to about +/- 10 A). Seven conditions whose tabulated parameters give a thickness more than
~8% from Figure 5 are left out (see LEFT_OUT)."""
import json, sys
from brush_profiles import profile, moment

LEFT_OUT = {
    ("KOAc100", "27.5"): "gives 570 A; Figure 5 shows about 395 A",
    ("KOAc100", "30"): "gives 311 A; Figure 5 shows about 370 A",
    ("KOAc250", "20"): "gives 632 A; Figure 5 shows about 468 A",
    ("KOAc250", "22.5"): "gives 523 A; Figure 5 shows about 418 A",
    ("KOAc250", "25"): "the table lists a Gaussian tail but no tail parameters",
    ("KOAc250", "35"): "gives 206 A; Figure 5 shows about 240 A",
    ("KSCN100", "32.5"): "gives 372 A; Figure 5 shows about 340 A",
}
NAMES = {"D2O": "D₂O", "KOAc100": "100 mM KOAc", "KOAc250": "250 mM KOAc", "KSCN100": "100 mM KSCN", "KSCN250": "250 mM KSCN"}
STEP, ZMAX = 4, 1000

data = json.load(open(sys.argv[1]))
out = []
for key, temps in data.items():
    if key.startswith("_"):
        continue
    rows = []
    for T, c in sorted(temps.items(), key=lambda kv: float(kv[0])):
        if (key, T) in LEFT_OUT:
            continue
        zs, ph = profile(c, 1400, STEP)
        n = ZMAX // STEP + 1
        rows.append({
            "T": float(T), "L": round(moment(zs, ph)), "tail": c.get("tail"), "slabs": len(c["slabs"]),
            "chi2": c["chi2"], "phi": [round(p, 3) for p in ph[:n]],
        })
    out.append({"id": key, "name": NAMES[key], "rows": rows})

left = [{"id": k, "T": float(T), "why": why} for (k, T), why in LEFT_OUT.items()]
with open(sys.argv[2], "w") as f:
    f.write("// Data for the brush scene in paper-visuals.js. Generated by build/brush_data.py; do not edit by hand.\n")
    f.write("// PNIPAM brush volume fraction profiles, Murdoch et al., Macromolecules 2016, 49, 6050, doi:10.1021/acs.macromol.6b01001,\n")
    f.write("// rebuilt from the fitted parameters in its Supporting Information (Tables S1-S5) with the paper's model.\n")
    f.write(f"// phi is sampled every {STEP} A from the grafting surface to {ZMAX} A. L is twice the first moment (A).\n")
    f.write(f"export const BRUSH_STEP = {STEP};\n")
    f.write("export const BRUSH = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("export const BRUSH_LEFT_OUT = " + json.dumps(left, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(sum(len(s["rows"]) for s in out), "profiles;", len(left), "left out")
