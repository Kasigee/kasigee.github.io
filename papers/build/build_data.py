"""Write paper-data.js for the paper visuals from the checked source data."""
import json, sys
import numpy as np

B = sys.argv[1]
OUT = sys.argv[2]

# Chem. Sci. 2021, 12, 15007, ESI Table S2 (site-specific rows). r: cube root of <r^3> (A); q: site charge (e);
# rho: site-specific radial charge density (1e-10 C m^-1); ue: ion-water electrostatic energy (kJ mol^-1).
